import { expect, test } from '@playwright/test'

test('发布记录、下载、重新登录、原地址更新与撤销', async ({ page, request }) => {
  const login = async () => {
    await page.getByLabel('管理员账号').fill('admin')
    await page.getByLabel('密码', { exact: true }).fill('test-password-12345')
    await page.getByRole('button', { name: '登录', exact: true }).click()
  }
  await page.goto('/converter')
  await login()
  await page.getByRole('button', { name: '新建转换' }).click()
  await page.getByLabel('订阅名称').click()
  await page.getByLabel('订阅名称').fill('浏览器转换记录')
  await expect(page.getByLabel('订阅名称')).toHaveValue('浏览器转换记录')
  const input = page.getByLabel('订阅内容')
  await input.fill('vless://example@127.0.0.1:443?security=tls&type=grpc&serviceName=old#手机')
  await page.getByRole('button', { name: '预览转换' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载 YAML' }).click()
  expect((await download).suggestedFilename()).toMatch(/\.yaml$/)
  await page.getByRole('button', { name: '发布在线订阅' }).click()
  const url = await page.getByLabel('在线订阅地址').inputValue()
  expect(await (await request.get(url)).text()).toContain('grpc-service-name: old')
  await page.getByRole('button', { name: '节点测速' }).click()
  const probe = page.getByRole('dialog', { name: '节点测速 · 浏览器转换记录' })
  const node = probe.getByRole('row').filter({ has: page.getByRole('cell', { name: '手机', exact: true }) })
  await node.locator('label').click()
  await expect(node.getByRole('checkbox')).toBeChecked()
  await probe.getByRole('button', { name: '测速选中 (1)' }).click()
  await expect(node.getByText('失败', { exact: true })).toBeVisible()
  await expect(node.getByText('仅端口')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(probe).toBeHidden()
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page.getByLabel('管理员账号')).toBeVisible()
  await page.goto('/converter')
  await login()
  await expect(page.getByRole('heading', { name: '在线记录' })).toBeVisible()
  await page.reload()
  await page.getByRole('article').filter({ hasText: '浏览器转换记录' }).getByRole('button', { name: '节点测速' }).click()
  await expect(node.getByText('失败', { exact: true })).toBeVisible()
  await expect(probe.getByRole('button', { name: '全部测速' })).toBeEnabled()
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: '浏览器转换记录' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '编辑记录' }).click()
  await input.fill((await input.inputValue()).replace('grpc-service-name: old', 'grpc-service-name: new'))
  await page.getByRole('button', { name: '预览转换' }).click()
  await expect(page.getByText('新增 0 · 移除 0 · 修改 1')).toBeVisible()
  await page.getByRole('button', { name: '保存到原订阅' }).click()
  await expect(page.getByLabel('在线订阅地址')).toHaveValue(url)
  expect(await (await request.get(url)).text()).toContain('grpc-service-name: new')
  await page.getByRole('button', { name: '停用', exact: true }).click()
  await expect(page.getByRole('button', { name: '恢复', exact: true })).toBeVisible()
  expect((await request.get(url)).status()).toBe(404)
  await page.getByRole('button', { name: '恢复', exact: true }).click()
  await expect(page.getByRole('button', { name: '停用', exact: true })).toBeVisible()
  expect((await request.get(url)).status()).toBe(200)
  await page.getByRole('button', { name: '删除记录', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: /确定|确认|OK/i }).click()
  await expect(page.getByRole('heading', { name: '在线记录' })).toBeVisible()
  expect((await request.get(url)).status()).toBe(404)
})
