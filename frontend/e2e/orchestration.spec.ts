import { test, expect } from '@playwright/test'

const headers = { Authorization: 'Bearer e2e-synthetic-api-key-00000000000000000000' }
test.afterEach(async ({ request }) => {
  for (const kind of ['chain-templates', 'subscriptions', 'chains', 'entries', 'exits', 'subscriptions', 'sources']) {
    const rows = await (await request.get('/api/v1/' + kind, { headers })).json()
    for (const row of rows) if (row.name.startsWith('编排验收')) await request.delete('/api/v1/' + kind + '/' + row.id, { headers })
  }
})

test('多跳编辑、主备、模板、草稿、批量及响应式', async ({ page, request }) => {
  test.setTimeout(90000)
  async function post(path: string, data: unknown) {
    const response = await request.post('/api/v1' + path, { headers, data })
    expect(response.ok(), await response.text()).toBeTruthy()
    return response.json()
  }
  const resources = []
  for (let i = 0; i < 4; i++) resources.push(await post('/exits', { name: '编排验收代理' + i, server: 'proxy' + i + '.invalid', port: 8080 }))
  const chain = await post('/chains', { name: '编排验收多跳', enabled: false, monitor_enabled: false,
    paths: [{ name: '主路径', strategy: 'fixed', hops: resources.slice(0, 3).map(r => ({ source: 'proxy', ref: r.id })) }] })
  await page.goto('/login')
  await page.getByLabel('管理员账号').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('test-password-12345')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '连接总览', exact: true })).toBeVisible()
  await page.goto('/chains/' + chain.id + '/edit')
  await expect(page.locator('.hop-card')).toHaveCount(3)
  await page.getByRole('button', { name: '在第 2 跳后添加节点', exact: true }).click()
  await page.getByRole('combobox', { name: '选择节点资源', exact: true }).click()
  await page.getByRole('option', { name: '编排验收代理3 · http', exact: true }).click()
  await page.getByRole('button', { name: '前移第 3 跳', exact: true }).click()
  await expect(page.locator('.hop-card').nth(1)).toContainText('编排验收代理3')
  await page.getByRole('button', { name: '复制为备用路径', exact: true }).click()
  await expect(page.getByRole('tab', { name: /备用 1/ })).toBeVisible()
  await page.getByRole('button', { name: '校验配置', exact: true }).click()
  await expect(page.getByText('配置已校验', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '模板操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '保存为模板', exact: true }).click()
  await page.getByRole('dialog').getByRole('textbox').fill('编排验收模板')
  await page.getByRole('dialog').getByRole('button', { name: /确定|确认/ }).click()
  await page.getByRole('button', { name: '检测草稿', exact: true }).click()
  const diagnostic = page.getByRole('dialog', { name: '草稿检测', exact: true })
  await expect(diagnostic).toContainText('配置或内核', { timeout: 15000 })
  await diagnostic.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '返回链路', exact: true }).click()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(page.locator('.hop-card')).toHaveCount(4)
  for (const theme of ['light', 'dark']) {
    await page.evaluate(t => { document.documentElement.classList.toggle('dark', t === 'dark') }, theme)
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    }
  }
  await page.getByRole('button', { name: '保存链路', exact: true }).click()
  await expect(page).toHaveURL(/\/chains$/)
  const saved = await (await request.get('/api/v1/chains/' + chain.id, { headers })).json()
  expect(saved.paths).toHaveLength(2)
  expect(saved.paths[0].hops.map((h: { ref: string }) => h.ref)).toEqual([resources[0].id, resources[3].id, resources[1].id, resources[2].id])
  expect(saved.enabled).toBe(false)
  const card = page.locator('.chain-card').filter({ has: page.getByRole('heading', { name: '编排验收多跳', exact: true }) })
  await expect(card).toContainText('已停用')
  await expect(card).toContainText('+1 条备用路径')
  await card.locator('.chain-check').click()
  await expect(page.getByRole('toolbar', { name: '批量操作' })).toContainText('已选 1 条')
  await page.getByRole('button', { name: '开启监控', exact: true }).click()
  await expect(page.locator('.batch-results')).toContainText('完成')
  await card.getByRole('button', { name: '更多操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '监控与事件', exact: true }).click()
  const drawer = page.locator('.chain-drawer')
  await expect(drawer.getByRole('tab', { name: '监控与事件', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(drawer).toContainText('自动监控已开启')
  await drawer.getByRole('tab', { name: '概览', exact: true }).click()
  await expect(drawer).toContainText('备用 1')
})

test('内联创建入口与代理、模板套用及键盘保存', async ({ page, request }) => {
  async function post(path: string, data: unknown) {
    const response = await request.post('/api/v1' + path, { headers, data })
    expect(response.ok()).toBeTruthy()
    return response.json()
  }
  const source = await post('/sources/file', { name: '编排验收内联源', content: 'proxies:\n - {name: entry, type: http, server: entry.invalid, port: 8080}' })
  await post('/subscriptions', { name: '编排验收内联订阅', source_ids: [source.id] })
  await page.goto('/login')
  await page.getByLabel('管理员账号').fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('test-password-12345')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '连接总览', exact: true })).toBeVisible()
  await page.goto('/chains/new')
  await page.getByLabel('链路名称', { exact: true }).fill('编排验收内联链路')
  await page.getByRole('button', { name: '新建入口池', exact: true }).click()
  const entryDialog = page.getByRole('dialog', { name: '新建入口池', exact: true })
  await entryDialog.getByLabel('资源名称').fill('编排验收内联入口')
  await entryDialog.getByRole('combobox', { name: '资源来源订阅' }).press('Enter')
  await page.getByRole('option', { name: '编排验收内联订阅', exact: true }).click()
  await entryDialog.getByRole('button', { name: '保存并选中' }).click()
  await expect(page.locator('.hop-card').first()).toContainText('编排验收内联入口')
  await page.locator('.hop-card').last().locator('.hop-select').click()
  await page.getByRole('button', { name: '添加代理', exact: true }).click()
  const proxyDialog = page.getByRole('dialog', { name: '添加代理', exact: true })
  await proxyDialog.getByLabel('资源名称').fill('编排验收内联出口')
  await proxyDialog.getByLabel('代理服务器').fill('inline-exit.invalid')
  await proxyDialog.getByRole('button', { name: '保存并选中' }).click()
  await expect(page.locator('.hop-card').last()).toContainText('编排验收内联出口')
  await page.getByRole('button', { name: '模板操作', exact: true }).click()
  await page.getByRole('menuitem', { name: '保存为模板', exact: true }).click()
  await page.getByRole('dialog').getByRole('textbox').fill('编排验收内联模板')
  await page.getByRole('dialog').getByRole('button', { name: /确定|确认/ }).click()
  await page.locator('.el-switch').filter({ hasText: '保存后启用' }).locator('.el-switch__core').click()
  await expect(page.getByRole('switch', { name: '保存后启用' })).toHaveAttribute('aria-checked', 'false')
  await page.keyboard.press('Control+s')
  await expect(page).toHaveURL(/\/chains$/)
  await page.getByRole('button', { name: '链路模板', exact: true }).click()
  await page.getByRole('dialog', { name: '链路模板', exact: true }).getByRole('button', { name: '套用并编辑', exact: true }).click()
  await expect(page.getByLabel('链路名称', { exact: true })).toHaveValue('编排验收内联模板')
  await expect(page.locator('.hop-card').first()).toContainText('编排验收内联入口')
  await expect(page.locator('.hop-card').last()).toContainText('编排验收内联出口')
  await page.getByRole('button', { name: '保存链路', exact: true }).click()
  await expect(page).toHaveURL(/\/chains$/)
  const rows = await (await request.get('/api/v1/chains', { headers })).json()
  expect(rows.filter((c: { name: string }) => c.name.startsWith('编排验收内联'))).toHaveLength(2)
})
